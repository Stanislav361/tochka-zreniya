export type PriceTab = (typeof priceTabs)[number];

export function getServiceTab(service: Service): PriceTab {
  const { code, category } = service;
  if (code.startsWith("Д-")) return "Годовые программы";
  if (["К-2", "К-5", "К-6", "К-7"].includes(code)) return "Школьные & Детские комплексы";
  if (["К-1", "К-3", "К-4", "К-8"].includes(code)) return "Диагностические комплексы";
  if (category === "Офтальмология: оптика") return "Оптика & Подбор линз";
  if (category === "Офтальмология: аппаратное лечение") return "Аппаратное лечение";
  if (category === "Пульмонология" || category === "Эндокринология") return "Пульмонология & Эндокринология";
  return "Офтальмология: Приемы & Диагностика";
}

